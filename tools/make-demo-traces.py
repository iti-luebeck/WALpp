#!/usr/bin/env python3
"""Generates the small VCD traces used by the documentation playground.

They are committed under docs/playground/traces, so this only needs running when the
example set changes. Kept deliberately small: the playground fetches them on every
page visit, and both WAL++ and Surfer parse them in the browser.

Note the two things a VCD writer must get right, which the old tests/sample.vcd got
wrong and which made Surfer's parser (wellen) abort:
  * `$enddefinitions` must be followed by `$end`
  * a vector value is `b<bits> <id>`, with the `b` prefix and the space, in $dumpvars too
"""
import os

IDS = "!\"#$%&'()*+,-./"


def write_vcd(path, scope, variables, rows, timescale="1ns", version="WAL++ documentation playground"):
    ids = {name: IDS[i] for i, (name, _) in enumerate(variables)}
    out = ["$date", "    Generated by tools/make-demo-traces.py", "$end",
           "$version", f"    {version}", "$end",
           f"$timescale {timescale} $end",
           f"$scope module {scope} $end"]
    for name, width in variables:
        out.append(f"$var wire {width} {ids[name]} {name} $end")
    out += ["$upscope $end", "$enddefinitions $end", "$dumpvars"]
    for name, width in variables:
        out.append(f"0{ids[name]}" if width == 1 else "b" + "0" * width + f" {ids[name]}")
    out.append("$end")

    previous = {name: None for name, _ in variables}
    for time, values in rows:
        out.append(f"#{time}")
        for name, width in variables:
            value = values.get(name)
            if value is None or value == previous[name]:
                continue
            previous[name] = value
            out.append(f"{value}{ids[name]}" if width == 1
                       else "b{:0{}b} {}".format(value, width, ids[name]))
    with open(path, "w") as handle:
        handle.write("\n".join(out) + "\n")
    print(f"wrote {path}")


def handshake(path):
    """A ready/valid handshake carrying a byte stream: stalls, bursts, idle gaps."""
    payload = [0x00, 0x3C, 0xA5, 0xFF, 0x10, 0x7E, 0x42, 0x99, 0x01, 0xC3, 0x5A, 0x80]
    rows, time = [], 0
    for i in range(64):
        beat = i // 4
        rows.append((time, {
            "clk": i % 2,
            "data": payload[beat % len(payload)],
            "valid": 1 if beat % 4 != 3 else 0,
            "ready": 1 if beat % 3 != 2 else 0,
        }))
        time += 5
    write_vcd(path, "dut", [("clk", 1), ("data", 8), ("valid", 1), ("ready", 1)], rows)


def fabric(path):
    """Three ready/valid interfaces in one scope, so `groups` has something to find.

    Shaped like the WAL manual's own groups example, which uses name prefixes
    (top.in_, top.out_) rather than separate scopes. Each interface completes a
    different number of transactions, so a per-group answer is visibly per-group
    rather than the same number three times.
    """
    rows, time = [], 0
    # (prefix, valid period, ready period): different duty cycles, different counts
    ports = [("in", 2, 3), ("out", 3, 5), ("cmd", 6, 7)]
    for i in range(96):
        beat = i // 2
        values = {"clk": i % 2}
        for index, (prefix, vper, rper) in enumerate(ports):
            values[f"{prefix}_valid"] = 1 if beat % vper != vper - 1 else 0
            values[f"{prefix}_ready"] = 1 if beat % rper != rper - 1 else 0
            values[f"{prefix}_data"] = (beat * (index + 3)) % 256
        rows.append((time, values))
        time += 5
    variables = [("clk", 1)]
    for prefix, _, _ in ports:
        variables += [(f"{prefix}_valid", 1), (f"{prefix}_ready", 1), (f"{prefix}_data", 8)]
    write_vcd(path, "top", variables, rows)


def counter(path):
    """A free running 8 bit counter: every carry is a burst of toggling bits."""
    rows, time = [], 0
    for i in range(160):
        tick = i // 2
        rows.append((time, {
            "clk": i % 2,
            "count": tick % 256,
            "carry": 1 if tick % 16 == 15 else 0,
        }))
        time += 5
    write_vcd(path, "cpu", [("clk", 1), ("count", 8), ("carry", 1)], rows)


if __name__ == "__main__":
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                        "docs", "playground", "traces")
    os.makedirs(here, exist_ok=True)
    handshake(os.path.join(here, "handshake.vcd"))
    counter(os.path.join(here, "counter.vcd"))
    fabric(os.path.join(here, "fabric.vcd"))
